// Regenerates font-metrics.json: per-character advance widths (1/1000 em) for regular and bold, taking the
// MAXIMUM over every font in the declared stack that is installed here. figkit measures text with this table,
// so a label that fits here fits whichever of those fonts a reader's machine resolves.
// usage: node measure_fonts.mjs [--fonts '"Helvetica Neue",Helvetica,Arial'] [--out font-metrics.json]
// Re-run whenever the design system's font stack changes: the stack is layout, not style.
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
import { launch, closeFast } from './pw.mjs';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2); const opt = k => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : null; };
const FONTS = (opt('--fonts') || '"Helvetica Neue",Helvetica,Arial,"Liberation Sans","Segoe UI",Roboto,"DejaVu Sans"')
  .split(',').map(s => s.trim()).filter(Boolean)
  // canvas does not accept the -apple-system / BlinkMacSystemFont keywords: measure the system face they name
  .map(f => /^(-apple-system|BlinkMacSystemFont)$/.test(f) ? 'system-ui' : f);
const OUT = opt('--out') || path.join(HERE, 'font-metrics.json');
const chars = []; for (let c = 32; c < 127; c++) chars.push(String.fromCharCode(c));
chars.push(...'•–—‘’“”…×÷→←↑↓−·éèàçüöäñ½≈≤≥€£°§▸◂✓✕²³'.split(''));
const b = await launch(); const p = await b.newPage();
const res = await p.evaluate(({ FONTS, chars }) => {
  const c = document.createElement('canvas').getContext('2d');
  const installed = f => {
    c.font = `100px ${f}, monospace`; const a = c.measureText('mmmmiiiilW').width;
    c.font = '100px monospace'; return f === 'system-ui' || Math.abs(a - c.measureText('mmmmiiiilW').width) > 0.5;
  };
  const used = FONTS.filter(installed); const out = { fonts: used, regular: {}, bold: {} };
  for (const [w, key] of [[400, 'regular'], [700, 'bold']]) for (const ch of chars) {
    let m = 0; for (const f of used) { c.font = `${w} 1000px ${f}`; m = Math.max(m, c.measureText(ch).width); }
    out[key][ch] = Math.round(m);
  }
  return out;
}, { FONTS, chars });
await closeFast(b);
if (!res.fonts.length) { console.error('none of the fonts in the stack is installed; metrics not written'); process.exit(1); }
res.stack = FONTS;
res.note = 'Advance widths in 1/1000 em, maximum across the installed fonts listed. Generated by measure_fonts.mjs.';
fs.writeFileSync(OUT, JSON.stringify(res));
console.log('fonts measured:', res.fonts.join(', '), '| chars:', Object.keys(res.regular).length, '|', OUT);
process.exit(0);
